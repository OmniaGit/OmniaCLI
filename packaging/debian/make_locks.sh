#!/bin/bash
# Resolve, in a container of every target distribution, the newest versions of
# OmniaCI's dependencies that its system python3 accepts, write them as a lock
# file requirements/py<major><minor>.txt, and run the test suite against them.
# The package installs the lock that matches the Python of its venv (Debian 11,
# with Python 3.9, gets a Python 3.12 and its py312 lock: see postinst).
#
# Usage: packaging/debian/make_locks.sh [image ...]
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
IMAGES=("$@")
[ ${#IMAGES[@]} -gt 0 ] || IMAGES=(ubuntu:22.04 debian:12 ubuntu:24.04 debian:13)
# the direct dependencies; the lock pins them and everything they pull in
DIRECT="fastapi uvicorn jinja2 pyyaml mcp"
TEST_DEPS="pytest pytest-asyncio httpx"

lock_one() {
    local image="$1" log="$HERE/requirements/.${1//[:\/]/_}.log"
    docker run --rm -v "$ROOT:/src:ro" -v "$HERE/requirements:/out" "$image" bash -c "
        set -euo pipefail
        export DEBIAN_FRONTEND=noninteractive
        # bullseye left LTS: deb.debian.org answers 404 for its security pool
        # (checked 2026-10-20), archive.debian.org still serves it
        if grep -q '^11' /etc/debian_version; then
            sed -i 's#http://deb.debian.org/debian-security#http://archive.debian.org/debian-security#' /etc/apt/sources.list
        fi
        apt-get update -qq && apt-get install -y -qq python3-venv git >/dev/null
        py=\$(python3 -c 'import sys; print(f\"py{sys.version_info[0]}{sys.version_info[1]}\")')
        python3 -m venv /venv
        /venv/bin/pip install -q --disable-pip-version-check $DIRECT
        {
            echo \"# OmniaCI runtime dependencies for \$(python3 -V) ($image)\"
            echo '# generated by packaging/debian/make_locks.sh, do not edit'
            /venv/bin/pip freeze --all --exclude-editable | grep -viE '^(pip|setuptools|wheel|pkg[-_]resources)=='
        } > /out/\$py.txt.tmp
        # the test suite, against exactly these versions
        /venv/bin/pip install -q --disable-pip-version-check -r /out/\$py.txt.tmp $TEST_DEPS
        cp -r /src /work && cd /work && rm -rf .pytest_cache
        PYTHONPATH=/work /venv/bin/python -m pytest -q -p no:cacheprovider 2>&1 | tail -3
        mv /out/\$py.txt.tmp /out/\$py.txt
        echo \"\$py written\"
    " > "$log" 2>&1 && echo "$image: $(tail -1 "$log") | $(grep -E 'passed|failed|error' "$log" | tail -1)" \
                    || { echo "$image: FAILED, see $log"; tail -20 "$log"; return 1; }
}

status=0
for image in "${IMAGES[@]}"; do
    lock_one "$image" &
done
for job in $(jobs -p); do wait "$job" || status=1; done
exit $status
